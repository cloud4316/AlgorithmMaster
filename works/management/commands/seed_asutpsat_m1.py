class Command(BaseCommand):
    help = 'Seed Технологии автоматизации технологических процессов — 5 модулей АСУ ТП'

    def handle(self, *args, **kwargs):
        subject, created = Subject.objects.get_or_create(
            slug='asutps',
            defaults={
                'title': 'Технологии автоматизации технологических процессов',
                'description': 'Автоматизированные системы управления технологическими процессами',
            },
        )
        subject.title = 'Технологии автоматизации технологических процессов'
        subject.save()
        if created:
            self.stdout.write(f'Created subject: {subject.title}')
        else:
            self.stdout.write(f'Subject exists: {subject.title} (id={subject.id})')

        for mod_data in MODULES:
            module, _ = TheoryModule.objects.get_or_create(
                subject=subject,
                order=mod_data['order'],
                defaults={
                    'title': mod_data['title'],
                    'icon': mod_data['icon'],
                    'description': mod_data['description'],
                },
            )
            module.title = mod_data['title']
            module.icon = mod_data['icon']
            module.description = mod_data['description']
            module.save()
            self.stdout.write(f'  Module {module.order}: {module.title}')

            for les_data in mod_data['lessons']:
                lesson, _ = TheoryLesson.objects.get_or_create(
                    module=module,
                    order=les_data['order'],
                    defaults={
                        'title': les_data['title'],
                        'estimated_minutes': les_data['estimated_minutes'],
                        'content': les_data['content'],
                    },
                )
                lesson.title = les_data['title']
                lesson.estimated_minutes = les_data['estimated_minutes']
                lesson.content = les_data['content']
                lesson.save()
                self.stdout.write(f'    Lesson {lesson.order}: {lesson.title}')

        self.stdout.write(self.style.SUCCESS('Done.'))
