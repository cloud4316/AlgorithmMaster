class Command(BaseCommand):
    help = 'Expand MCU M16-M17: увеличить до 6 уроков с подробным содержимым'

    def handle(self, *args, **options):
        subject = Subject.objects.filter(slug='mcu').first()
        if not subject:
            self.stderr.write('Subject mcu not found')
            return

        for order, title, lessons in [
            (16, 'История развития МП и классификация МПС', M16_LESSONS),
            (17, 'Принстонская и Гарвардская архитектуры МПС', M17_LESSONS),
        ]:
            module = TheoryModule.objects.filter(subject=subject, order=order).first()
            if not module:
                self.stderr.write(f'Module M{order} not found')
                continue
            module.title = title
            module.save()
            for lesson in lessons:
                obj, created = TheoryLesson.objects.update_or_create(
                    module=module,
                    order=lesson['order'],
                    defaults={**lesson, 'module': module},
                )
                tag = 'created' if created else 'updated'
                self.stdout.write(f'  M{order} урок {lesson["order"]}: {lesson["title"]} [{tag}]')
            self.stdout.write(f'Module M{order}: {len(lessons)} lessons done')

        self.stdout.write(self.style.SUCCESS('Done: M16-M17 expanded'))
