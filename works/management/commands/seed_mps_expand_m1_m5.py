class Command(BaseCommand):
    help = 'Add new lessons to MPS modules 1-5'

    def handle(self, *args, **options):
        try:
            subj = Subject.objects.get(title='Микропроцессорные системы')
        except Subject.DoesNotExist:
            self.stdout.write('ERROR: Subject not found')
            return

        total_created = 0

        for module_title, lessons in LESSONS.items():
            try:
                module = subj.modules.get(title=module_title)
            except TheoryModule.DoesNotExist:
                self.stdout.write(f'  SKIP: module "{module_title}" not found')
                continue

            # Determine next order value
            max_order = module.lessons.aggregate(m=Max('order'))['m'] or 0
            next_order = max_order + 1

            for lesson_data in lessons:
                obj, created = TheoryLesson.objects.get_or_create(
                    module=module,
                    title=lesson_data['title'],
                    defaults={
                        'content': lesson_data['content'].strip(),
                        'code_example': lesson_data['code_example'].strip(),
                        'order': next_order,
                        'estimated_minutes': lesson_data['estimated_minutes'],
                    }
                )
                if created:
                    total_created += 1
                    self.stdout.write(f'  + [{module_title}] {obj.title} (order={next_order})')
                    next_order += 1
                else:
                    self.stdout.write(f'  = [{module_title}] {obj.title} (exists)')

        self.stdout.write(f'\nDone. Created {total_created} new lessons.')
