# ── Вспомогательные функции ──────────────────────────────────────────────────

def tip(text):
    return f'<div class="tip">💡 {text}</div>'

def warn(text):
    return f'<div class="warning">⚠️ {text}</div>'

def code(text):
    return f'<pre><code>{text}</code></pre>'

def h(level, text):
    return f'<h{level}>{text}</h{level}>'

def p(text):
    return f'<p>{text}</p>'

def ul(items):
    return '<ul>' + ''.join(f'<li>{i}</li>' for i in items) + '</ul>'


