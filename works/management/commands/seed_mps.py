# ── Команда ──────────────────────────────────────────────────────────────────

class Command(BaseCommand):
    help = 'Seed МПС content: theory modules, practical works, quizzes'

    def handle(self, *args, **kwargs):
        subject, _ = Subject.objects.get_or_create(
            slug='mcu',
            defaults={
                'title': 'Микропроцессорные системы',
                'icon': 'fas fa-microchip',
                'color': '#10b981',
                'order': 2,
                'is_active': True,
            }
        )
        self.stdout.write(f'Subject: {subject.title} (id={subject.id})')

        # ── Теория ──────────────────────────────────────────────────────
        total_mods, total_lessons = 0, 0
        for mod_data in MODULES:
            lessons_data = mod_data.pop('lessons')
            module, mod_created = TheoryModule.objects.update_or_create(
                order=mod_data['order'],
                subject=subject,
                defaults={**mod_data, 'subject': subject, 'is_active': True},
            )
            if mod_created:
                total_mods += 1

            for lesson_data in lessons_data:
                code_example = lesson_data.pop('code', '')
                _, les_created = TheoryLesson.objects.update_or_create(
                    module=module,
                    order=lesson_data['order'],
                    defaults={
                        'title': lesson_data['title'],
                        'content': lesson_data['content'],
                        'code_example': code_example,
                        'estimated_minutes': lesson_data.get('minutes', 45),
                    }
                )
                if les_created:
                    total_lessons += 1
            # Вернуть lessons обратно для следующего прохода (если будет)
            mod_data['lessons'] = lessons_data

        self.stdout.write(f'Theory: +{total_mods} modules, +{total_lessons} lessons')

        # ── Практика ────────────────────────────────────────────────────
        work_count = 0
        for w in WORKS:
            _, created = PracticalWork.objects.get_or_create(
                subject=subject,
                order=w['order'],
                defaults={
                    'title': w['title'],
                    'description': w['description'],
                    'subject': subject,
                    'max_score': w['max_score'],
                    'difficulty': w['difficulty'],
                    'is_active': True,
                }
            )
            if created:
                work_count += 1
        self.stdout.write(f'Works: +{work_count} practical works')

        # ── Тесты ───────────────────────────────────────────────────────
        quiz_count, q_count = 0, 0
        for qdata in QUIZZES:
            try:
                module = TheoryModule.objects.get(subject=subject, order=qdata['module_order'])
            except TheoryModule.DoesNotExist:
                continue
            quiz, qz_created = Quiz.objects.get_or_create(
                module=module,
                defaults={
                    'title': f'Тест: {module.title}',
                    'description': f'Проверь знания по теме: {module.title}',
                    'pass_score': 70,
                    'is_active': True,
                    'order': module.order,
                }
            )
            if qz_created:
                quiz_count += 1
            for i, q in enumerate(qdata['questions'], 1):
                question, q_created = Question.objects.get_or_create(
                    quiz=quiz, order=i,
                    defaults={'text': q['text'], 'q_type': 'single', 'explanation': q.get('exp', '')}
                )
                if q_created:
                    q_count += 1
                for j, (text, correct) in enumerate(q['choices'], 1):
                    AnswerChoice.objects.get_or_create(
                        question=question, order=j,
                        defaults={'text': text, 'is_correct': correct}
                    )
        self.stdout.write(f'Quizzes: +{quiz_count} quizzes, +{q_count} questions')
        self.stdout.write('MPS seed complete.')
