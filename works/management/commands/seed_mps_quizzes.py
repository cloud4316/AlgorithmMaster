"""python manage.py seed_mps_quizzes
Создаёт тесты Q11-Q15 для новых модулей МПС и расширяет Q1-Q10 до 6 вопросов.
"""
from django.core.management.base import BaseCommand
from works.models import TheoryModule, Quiz, Question, AnswerChoice, Subject


# helper
def make_q(quiz, order, text, choices, correct_idx, explanation=''):
    """choices = list of str, correct_idx = 0-based index"""
    q, _ = Question.objects.update_or_create(
        quiz=quiz, order=order,
        defaults={'text': text, 'explanation': explanation}
    )
    for i, c in enumerate(choices):
        AnswerChoice.objects.update_or_create(
            question=q, order=i+1,
            defaults={'text': c, 'is_correct': (i == correct_idx)}
        )
    return q


