class Command(BaseCommand):
    help = 'Создаёт тесты Q11-Q15 для МПС и расширяет Q1-Q10 до 6 вопросов'

    def handle(self, *args, **options):
        subj = Subject.objects.get(slug='mcu')
        mods = {m.order: m for m in TheoryModule.objects.filter(subject=subj)}

        # 1. Расширить Q1-Q10
        self.stdout.write('--- Расширение Q1-Q10 ---')
        for mod_order, extra in EXTRA_QUESTIONS.items():
            module = mods.get(mod_order)
            if not module:
                continue
            quiz = Quiz.objects.filter(module=module).first()
            if not quiz:
                self.stderr.write(f'Тест для M{mod_order} не найден')
                continue
            for q_order, text, choices, correct, expl in extra:
                make_q(quiz, q_order, text, choices, correct, expl)
                self.stdout.write(f'  Q{quiz.order} вопрос {q_order}: добавлен')

        # 2. Создать Q11-Q15
        self.stdout.write('--- Создание Q11-Q15 ---')
        for mod_order, qdata in NEW_QUIZZES.items():
            module = mods.get(mod_order)
            if not module:
                self.stderr.write(f'M{mod_order} не найден')
                continue
            quiz, created = Quiz.objects.update_or_create(
                module=module,
                defaults={
                    'title': qdata['title'],
                    'description': qdata['description'],
                    'order': mod_order,
                    'pass_score': 70,
                    'is_active': True,
                }
            )
            status = 'создан' if created else 'обновлён'
            self.stdout.write(f'Q{mod_order} M{mod_order} [{status}]: {qdata["title"]}')
            for i, (text, choices, correct, expl) in enumerate(qdata['questions'], 1):
                make_q(quiz, i, text, choices, correct, expl)
                self.stdout.write(f'  вопрос {i}: OK')

        # Итог
        for mod_order in list(EXTRA_QUESTIONS.keys()) + list(NEW_QUIZZES.keys()):
            m = mods.get(mod_order)
            if m:
                q = Quiz.objects.filter(module=m).first()
                if q:
                    self.stdout.write(f'Q{mod_order}: {q.questions.count()} вопросов')

        self.stdout.write(self.style.SUCCESS('Готово!'))
