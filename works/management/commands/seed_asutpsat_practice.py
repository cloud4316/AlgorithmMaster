class Command(BaseCommand):
    help = 'Seed ASUTPSAT practical works'

    def handle(self, *args, **kwargs):
        subject = Subject.objects.get(title='АСУТП')
        module = TheoryModule.objects.get(subject=subject, order=1)

        for w in WORKS:
            work, created = PracticalWork.objects.get_or_create(
                subject=subject,
                order=w['order'],
                defaults={
                    'title': w['title'],
                    'description': w['description'],
                    'difficulty': w['difficulty'],
                    'max_score': w['max_score'],
                    'topic': w['topic'],
                    'language': w['language'],
                    'input_example': w.get('input_example', ''),
                    'output_example': w.get('output_example', ''),
                    'theory_module': module,
                    'is_active': True,
                },
            )
            if not created:
                work.title = w['title']
                work.description = w['description']
                work.difficulty = w['difficulty']
                work.max_score = w['max_score']
                work.input_example = w.get('input_example', '')
                work.output_example = w.get('output_example', '')
                work.theory_module = module
                work.is_active = True
                work.save()
            status = 'created' if created else 'updated'
            self.stdout.write(f'  [{status}] ПЗ №{w["order"]}: {w["title"]}')

        self.stdout.write(self.style.SUCCESS(f'Done. {len(WORKS)} works seeded for АСУТП.'))
